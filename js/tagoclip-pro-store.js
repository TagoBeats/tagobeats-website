// Moonbase embedded storefront for /tagoclip-pro. Buy opens the checkout as an
// overlay on this page, Trial and Download hand the visitor the installer.
// Every button is a plain link to the hosted customer portal as well, so the
// page still sells if moonbase.js is blocked or fails to load.
(function () {
  "use strict";

  var ACCOUNT = "https://tagobeats.moonbase.sh";
  var PRODUCT = "tagoclip-pro";

  if (!window.Moonbase) return;

  // Only take over the clicks once the storefront has really loaded. Until
  // then (or if setup fails, e.g. CORS on a domain Moonbase does not know)
  // the links simply open the customer portal.
  var ready = false;
  Moonbase.setup(ACCOUNT, {
    // One product, no cart: the default "Log in | Cart" toolbar would only sit
    // on top of the page's own navigation.
    toolbar: { enabled: false },
    theme: {
      dark: true,
      // Shades and button colours as generated by the Moonbase dashboard
      // (Settings > Storefront > Theme) for the brand teal.
      colors: {
        primary: { 50: "#edfffc", 100: "#c0fff8", 200: "#81fff2", 300: "#3affec", 400: "#00fddc", 500: "#00e2c6", 600: "#00b7a4", 700: "#009184", 800: "#00726a", 900: "#045d57" },
        button: { background: "#00b7a4", text: "#000000", hover: "#1abead" },
        background: "gray"
      },
      fonts: { heading: { family: "Archivo, sans-serif" }, body: { family: "Archivo, sans-serif" } },
      corners: "soft",
      buttons: "light",
      cards: "outlined"
    },
    // No blur behind the overlay: backdrop blur is what broke scrolling on
    // this site before.
    checkout: { backdrop: { color: "dark", opacity: "standard", blur: false } }
  });
  // setup() resolves even when its data request is blocked, so readiness is
  // taken from the first successful data load instead.
  Moonbase.on("storefront-updated", function () { ready = true; });

  var ACTIONS = {
    buy: function () { Moonbase.purchase({ product_id: PRODUCT }); },
    // The trial starts inside the plugin (Activate, then Start trial), so the
    // page only has to deliver the installer.
    trial: function () { Moonbase.download_product({ product_id: PRODUCT }); },
    download: function () { Moonbase.download_product({ product_id: PRODUCT }); }
  };

  document.addEventListener("click", function (e) {
    var el = e.target.closest && e.target.closest("[data-tb-store]");
    if (!ready || !el || !ACTIONS[el.getAttribute("data-tb-store")]) return;
    e.preventDefault();
    ACTIONS[el.getAttribute("data-tb-store")]();
  });
})();
